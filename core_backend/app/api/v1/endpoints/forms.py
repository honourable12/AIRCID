# --- LLM Integration Endpoint ---
@router.post("/from-llm", response_model=FormRead, status_code=status.HTTP_201_CREATED, summary="Create a new form and questions from an LLM payload")
async def create_form_from_llm(
    llm_form_data: LLMFormSchema,
    session: AsyncSession = Depends(get_async_session),
    current_user: User = Depends(get_researcher_or_admin_user)
):
    """
    Create a new form and its questions using data from an LLM service.
    - The user must be a researcher who owns the study or an administrator.
    """
    # 1. Verify that the study exists
    study_query = await session.execute(select(Study).where(Study.id == llm_form_data.study_id))
    study = study_query.scalars().first()
    if not study:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Study not found")
    
    # 2. Check permissions
    if current_user.role.name == "researcher" and study.creator_id != current_user.id:
        raise HTTPException(status_code=status.HTTP_403_FORBIDDEN, detail="Not authorized to create forms for this study")

    # 3. Create the new Form
    new_form_data = FormCreate(
        study_id=llm_form_data.study_id,
        title=llm_form_data.title,
        description=llm_form_data.description
    )
    db_form = Form(**new_form_data.model_dump(), creator_id=current_user.id)
    session.add(db_form)
    await session.commit()
    await session.refresh(db_form)

    # 4. Create the questions and associate them with the new form
    for llm_question in llm_form_data.questions:
        # Determine the QuestionType enum from the string
        question_type = QuestionType[llm_question.question_type.upper()]
        
        # Create a new question
        new_question_data = QuestionCreate(
            form_id=db_form.id,
            question_text=llm_question.question_text,
            question_type=question_type,
            options=llm_question.options,
            is_required=llm_question.is_required
        )
        db_question = Question(**new_question_data.model_dump())
        session.add(db_question)

    await session.commit()
    await session.refresh(db_form, attribute_names=["questions"])
    
    # Eagerly load the questions for the final response
    result_refreshed = await session.execute(
        select(Form)
        .where(Form.id == db_form.id)
        .options(selectinload(Form.questions).selectinload(Question.options))
    )
    db_form_refreshed = result_refreshed.scalars().first()

    return db_form_refreshed